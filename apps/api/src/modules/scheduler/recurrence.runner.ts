import { Injectable, Logger } from '@nestjs/common';
import { EmploymentStatus, NotificationType, Prisma, TaskStatus, UserStatus } from '@prisma/client';
import { addDaysToKey, zonedDateKey, zonedTimeToUtc } from '@karban/shared';
import { PrismaService } from '../../prisma/prisma.service';
import { NotificationsService } from '../notifications/notifications.service';
import { RecurrenceService } from '../recurrence/recurrence.service';
import { RiskService } from '../risk/risk.service';
import { InjectConfig } from '../../config/config.module';
import type { AppConfig } from '../../config/config';
import { TasksService } from '../tasks/tasks.service';
import { TaskNotifier } from '../tasks/task-notifier';
import { dueOccurrences } from '../recurrence/recurrence.rules';

/** Creates task instances from recurrence templates (PRD §26). Idempotent per occurrence. */
@Injectable()
export class RecurrenceRunner {
  private readonly logger = new Logger(RecurrenceRunner.name);

  constructor(
    private readonly prisma: PrismaService,
    private readonly recurrence: RecurrenceService,
    private readonly tasks: TasksService,
    private readonly notifier: TaskNotifier,
    private readonly notifications: NotificationsService,
    private readonly risk: RiskService,
    @InjectConfig() private readonly config: AppConfig,
  ) {}

  async run(now = new Date()): Promise<number> {
    const tz = this.config.timeZone;
    const todayKey = zonedDateKey(now, tz);
    const rules = await this.prisma.recurrenceRule.findMany({
      where: { active: true, nextOccurrence: { lte: todayKey } },
      include: { primaryOwner: { include: { user: { select: { status: true } } } } },
    });
    const cal = await this.recurrence.calendar();
    let created = 0;
    for (const rule of rules) {
      const owner = rule.primaryOwner;
      if (owner.employmentStatus === EmploymentStatus.TERMINATED || owner.user?.status === UserStatus.DISABLED) {
        await this.prisma.recurrenceRule.update({ where: { id: rule.id }, data: { active: false } });
        await this.notifications.notify({
          employeeIds: [rule.managerId],
          type: NotificationType.OWNER_DEACTIVATED,
          title: `توقف وظیفه تکراری: ${rule.title}`,
          body: `مسئول وظیفه تکراری «${rule.title}» دیگر فعال نیست؛ تکرار متوقف شد. لطفاً مسئول جدید تعیین و تکرار را دوباره فعال کنید.`,
          link: '/recurring',
        });
        continue;
      }
      const { due, next } = dueOccurrences(rule, rule.nextOccurrence, todayKey, cal);
      for (const occurrence of due) {
        const h = Math.floor(rule.deadlineMinutes / 60);
        const m = rule.deadlineMinutes % 60;
        const deadline = zonedTimeToUtc(addDaysToKey(occurrence, rule.durationDays), h, m, tz);
        try {
          const task = await this.prisma.$transaction((tx) =>
            this.tasks.createWithin(
              tx,
              {
                title: rule.title,
                description: rule.description,
                creatorId: rule.creatorId,
                departmentId: rule.departmentId,
                primaryOwnerId: rule.primaryOwnerId,
                managerId: rule.managerId,
                collaboratorIds: rule.collaboratorIds,
                startDate: zonedTimeToUtc(occurrence, 0, 0, tz),
                deadline,
                priority: rule.priority,
                status: TaskStatus.NOT_STARTED,
                category: rule.category,
                tags: rule.tags,
                projectId: rule.projectId,
                estimatedEffortHours: rule.estimatedEffortHours,
                confidential: rule.confidential,
                requiresReview: rule.requiresReview,
                recurrenceId: rule.id,
                recurrenceOccurrence: occurrence,
              },
              null,
            ),
          );
          created++;
          await this.risk.refresh([task.id]).catch(() => undefined);
          await this.notifier.assigned(
            { ...task, collaboratorIds: rule.collaboratorIds },
            { employeeId: null, fullName: 'وظیفه تکراری' },
          );
          await this.notifier.collaboratorsAdded(
            { ...task, collaboratorIds: rule.collaboratorIds },
            rule.collaboratorIds,
            {
              employeeId: null,
              fullName: 'وظیفه تکراری',
            },
          );
        } catch (err) {
          // Unique (recurrenceId, occurrence) → already generated by a concurrent run.
          if (!(err instanceof Prisma.PrismaClientKnownRequestError && err.code === 'P2002')) throw err;
        }
      }
      await this.prisma.recurrenceRule.update({
        where: { id: rule.id },
        data: { nextOccurrence: next, lastRunAt: now, active: next !== null },
      });
    }
    if (created) this.logger.log(`Recurrence: created ${created} task instance(s)`);
    return created;
  }
}
